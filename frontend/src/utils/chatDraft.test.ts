import { cacheChatDraft, cacheChatDraftNow, clearCachedChatDraft, readCachedChatDraft, readCachedChatDrafts, cacheMessages, readCachedMessages } from "./sessionCache.ts";
import type { CacheableMessage } from "./sessionCache.ts";
const values = new Map<string, string>();
Object.defineProperty(globalThis, "localStorage", { configurable: true, value: {
  getItem: (key: string) => values.get(key) ?? null,
  setItem: (key: string, value: string) => values.set(key, value),
  removeItem: (key: string) => values.delete(key),
} });
let checks = 0;
function check(name: string, value: boolean) { if (!value) throw new Error(name); checks++; }
const token = "owner-a-secret";
values.set("mizan_token", token);
const old: CacheableMessage = { id: -1, role: "assistant", content: "  partial\n```python\n", ts: "", requestId: "A", messageId: "message-A", interrupted: true };
check("initial draft write succeeds", await cacheChatDraft("session", old, token));
check("partial draft survives reload with exact bytes and identity", (await readCachedChatDraft("session"))?.message.content === old.content && (await readCachedChatDraft("session"))?.message.messageId === "message-A");
check("token never appears in persisted draft key or value", [...values.entries()].filter(([key]) => key !== "mizan_token").every(([key, value]) => !key.includes(token) && !value.includes(token)));
check("draft snapshot is separate from completed-message cache", await readCachedMessages("session") === null);
const newest = { ...old, requestId: "B", messageId: "message-B", content: "new request partial" };
const writeB = cacheChatDraft("session", newest, token);
const clearA = clearCachedChatDraft("session", "A", token);
await Promise.all([writeB, clearA]);
check("late cleanup for A cannot invalidate an in-flight B write", (await readCachedChatDraft("session"))?.message.requestId === "B");
await clearCachedChatDraft("session", "A", token);
check("late A cleanup cannot erase already saved B", (await readCachedChatDraft("session"))?.message.requestId === "B");
const oldWrite = cacheChatDraft("session", { ...newest, content: "older partial" }, token);
const latestBytes = "  exact latest tail\n\n";
check("pagehide flush uses already prepared owner namespace", cacheChatDraftNow("session", { ...newest, content: latestBytes }, token));
await oldWrite;
check("an older async write cannot replace the immediate final snapshot", (await readCachedChatDraft("session"))?.message.content === latestBytes);
const pending = cacheChatDraft("session", newest, token);
const clearing = clearCachedChatDraft("session", "B", token);
await Promise.all([pending, clearing]);
check("same-request terminal cleanup invalidates pending stale writes", await readCachedChatDraft("session") === null);
await cacheChatDraft("session", old, token);
check("oversized draft is rejected without truncating existing received text", !(await cacheChatDraft("session", { ...newest, content: "x".repeat(1_000_001) }, token)) && (await readCachedChatDraft("session"))?.message.content === old.content);
await cacheChatDraft("other-session", newest, token);
check("drafts remain scoped to their own session", (await readCachedChatDraft("session"))?.message.requestId === "A" && (await readCachedChatDraft("other-session"))?.message.requestId === "B");
await cacheChatDraft("rapid-next", old, token);
await cacheChatDraft("rapid-next", newest, token);
const consecutive = await readCachedChatDrafts("rapid-next");
check("starting B before transcript debounce retains unsaved A and B by identity", consecutive.length === 2 && consecutive.some((row) => row.message.requestId === "A" && row.message.content === old.content) && consecutive.some((row) => row.message.requestId === "B"));
await clearCachedChatDraft("rapid-next", "B", token);
check("another run's saved terminal receipt cannot clear unsaved A", (await readCachedChatDrafts("rapid-next")).length === 1 && (await readCachedChatDraft("rapid-next"))?.message.requestId === "A");
await cacheChatDraft("bounded", { ...old, content: "a".repeat(750_000) }, token);
await cacheChatDraft("bounded", { ...newest, content: "b".repeat(750_000) }, token);
const rejectedLarge = await cacheChatDraft("bounded", { ...newest, requestId: "C", content: "c".repeat(750_000) }, token);
check("aggregate draft budget refuses a new write instead of evicting old unsaved text", !rejectedLarge && (await readCachedChatDrafts("bounded")).length === 2);
for (let i = 0; i < 8; i++) await cacheChatDraft("count-bound", { ...old, requestId: `request-${i}` }, token);
check("draft count is bounded without replacing an older request", !(await cacheChatDraft("count-bound", { ...old, requestId: "overflow" }, token)) && (await readCachedChatDrafts("count-bound")).length === 8);
const originalSet = localStorage.setItem;
localStorage.setItem = () => { throw new Error("Quota exceeded"); };
check("storage quota failure is reported to the UI instead of claiming a durable copy", !cacheChatDraftNow("session", { ...old, content: "not saved" }, token));
localStorage.setItem = originalSet;
check("failed quota write leaves existing received bytes intact", (await readCachedChatDraft("session"))?.message.content === old.content);
const switchedWrite = cacheChatDraft("session", newest, token);
values.set("mizan_token", "owner-b-secret");
await switchedWrite;
check("another owner cannot hydrate the old draft", await readCachedChatDraft("session") === null);
check("late old-owner pagehide cannot write under the new owner", !cacheChatDraftNow("session", newest, token));
check("late old-owner async write is rejected", !(await cacheChatDraft("session", newest, token)));
await cacheMessages("session", [old], token);
check("old-render message-cache timer cannot populate the new owner", await readCachedMessages("session") === null);
values.set("mizan_token", token);
const stopped = { ...old, stopped: true, interrupted: false };
await cacheChatDraft("session", stopped, token);
check("explicit Stop preserves exact bytes and proof of local action", (await readCachedChatDraft("session"))?.message.stopped === true && (await readCachedChatDraft("session"))?.message.content === old.content);
values.delete("mizan_token");
check("logged-out users cannot read pending drafts", await readCachedChatDraft("session") === null);
console.log(`${checks} draft recovery/privacy checks passed`);
