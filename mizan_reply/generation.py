"""Deterministic cached byte generation, with a UTF-8 *syntax* constraint.

This prevents malformed UTF-8, never false answers. A random/untrained model
will usually generate meaningless text. It has no built-in canned reply.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass

import torch
from torch import Tensor

from .model import ASSISTANT_ID, EOS_ID, MizanReplyModel


@dataclass(frozen=True)
class GenerationResult:
    text: str
    token_ids: list[int]
    stop_reason: str
    generated_tokens: int
    eos: bool

    def to_dict(self) -> dict:
        return asdict(self)


class UTF8State:
    """A strict Unicode-scalar UTF-8 automaton, excluding surrogates/overlongs."""

    def __init__(self) -> None:
        self.remaining = 0
        self.minimum = 0x80
        self.maximum = 0xBF

    def allowed(self, tokens_left: int, device: torch.device | str = "cpu") -> Tensor:
        if type(tokens_left) is not int or tokens_left < 1:
            raise ValueError("tokens_left must be a positive integer")
        if self.remaining > tokens_left:
            raise ValueError("insufficient budget to complete pending UTF-8 sequence")
        mask = torch.zeros(257, dtype=torch.bool, device=device)
        if self.remaining:
            mask[self.minimum:self.maximum + 1] = True
        else:
            mask[:0x80] = True
            mask[EOS_ID] = True
            if tokens_left >= 2:
                mask[0xC2:0xE0] = True
            if tokens_left >= 3:
                mask[0xE0:0xF0] = True
            if tokens_left >= 4:
                mask[0xF0:0xF5] = True
        return mask

    def consume(self, token: int) -> None:
        if type(token) is not int or not 0 <= token <= EOS_ID:
            raise ValueError("token must be a byte or EOS")
        if self.remaining:
            if not self.minimum <= token <= self.maximum:
                raise ValueError("invalid UTF-8 continuation")
            self.remaining -= 1
            self.minimum, self.maximum = 0x80, 0xBF
            return
        if token == EOS_ID or token < 0x80:
            return
        if 0xC2 <= token <= 0xDF:
            self.remaining = 1
        elif 0xE0 <= token <= 0xEF:
            self.remaining = 2
            if token == 0xE0:
                self.minimum = 0xA0
            elif token == 0xED:
                self.maximum = 0x9F
        elif 0xF0 <= token <= 0xF4:
            self.remaining = 3
            if token == 0xF0:
                self.minimum = 0x90
            elif token == 0xF4:
                self.maximum = 0x8F
        else:
            raise ValueError("invalid UTF-8 leading byte")


@torch.no_grad()
def generate(
    model: MizanReplyModel,
    input_ids: Tensor,
    roots: Tensor | None = None,
    max_new_tokens: int = 256,
) -> GenerationResult:
    """Generate one byte/EOS sequence, never silently truncating source context.

    ``input_ids`` is the data encoder's prompt [T] or [1,T], ending in the bare
    ASSISTANT marker. Only prefilling source bytes can carry root annotations.
    Every generated byte is stepped with roots=None. History is input context,
    not a weights update. ``max_new_tokens`` includes EOS if EOS is emitted.

    Total maximum inputs are prompt_length + max_new_tokens - 1, because the
    final prediction does not require feeding that prediction back to the model.
    """
    if not isinstance(model, MizanReplyModel):
        raise TypeError("model must be MizanReplyModel")
    if not isinstance(input_ids, Tensor) or input_ids.dtype != torch.int64:
        raise ValueError("input_ids must be an int64 tensor from encode_prompt")
    if input_ids.ndim == 1:
        input_ids = input_ids[None]
        if roots is not None:
            if not isinstance(roots, Tensor) or roots.ndim != 2:
                raise ValueError("unbatched prompt roots must have shape [time,4]")
            roots = roots[None]
    if input_ids.ndim != 2 or input_ids.shape[0] != 1 or input_ids.shape[1] < 1:
        raise ValueError("generate supports exactly one nonempty prompt at a time")
    if int(input_ids[0, -1]) != ASSISTANT_ID:
        raise ValueError("prompt must end in the encoder's ASSISTANT marker")
    if type(max_new_tokens) is not int or max_new_tokens < 1:
        raise ValueError("max_new_tokens must be a positive integer")
    if input_ids.shape[1] + max_new_tokens - 1 > model.config.max_seq_len:
        raise ValueError("requested prompt + output exceeds model context; no automatic truncation")
    original_modes = [(module, module.training) for module in model.modules()]
    model.eval()
    produced: list[int] = []
    utf8 = UTF8State()
    try:
        energies, cache = model.prefill(input_ids, roots)
        for index in range(max_new_tokens):
            if energies.shape != (1, 257) or not bool(torch.isfinite(energies).all()):
                raise ValueError("generation requires finite [1,257] energies")
            allowed = utf8.allowed(max_new_tokens - index, energies.device)
            token = int(energies[0].masked_fill(~allowed, float("inf")).argmin())
            utf8.consume(token)
            produced.append(token)
            if token == EOS_ID:
                break
            if index + 1 < max_new_tokens:
                energies = model.step(torch.tensor([token], device=input_ids.device, dtype=torch.int64), cache, roots=None)
        if utf8.remaining:
            raise RuntimeError("UTF-8 budget invariant failed")
        emitted_eos = bool(produced and produced[-1] == EOS_ID)
        raw = bytes(produced[:-1] if emitted_eos else produced)
        return GenerationResult(
            text=raw.decode("utf-8", errors="strict"),
            token_ids=produced,
            stop_reason="eos" if emitted_eos else "token_limit",
            generated_tokens=len(produced),
            eos=emitted_eos,
        )
    finally:
        # Preserve intentionally mixed module modes as well as the root flag.
        for module, training in original_modes:
            module.training = training
